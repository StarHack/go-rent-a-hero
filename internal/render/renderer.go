// WindowToLogical converts window-relative coordinates (as reported by SDL
// mouse events) to logical scene coordinates, accounting for the letterbox
// presentation, resizing and high-DPI scaling.
func (r *Renderer) WindowToLogical(windowX, windowY float32) (float32, float32) {
	var x, y float32
	sdl.RenderCoordinatesFromWindow(r.renderer, windowX, windowY, &x, &y)
	return x, y
}

// getTexture returns the cached GPU texture for (source, frame), decoding
// and uploading it on first use.
func (r *Renderer) getTexture(source engine.SpriteSource, frame int) (*sdl.Texture, error) {
	return r.getTextureVariant(source, frame, 0, 0, 0, false)
}

func (r *Renderer) getTextureKeyed(source engine.SpriteSource, frame int) (*sdl.Texture, error) {
	return r.getTextureVariant(source, frame, 0, 0, 0, true)
}

func (r *Renderer) getTextureCorrected(source engine.SpriteSource, frame, red, green, blue int) (*sdl.Texture, error) {
	return r.getTextureVariant(source, frame, red, green, blue, false)
}

func (r *Renderer) getTextureCorrectedKeyed(source engine.SpriteSource, frame, red, green, blue int) (*sdl.Texture, error) {
	return r.getTextureVariant(source, frame, red, green, blue, true)
}

func (r *Renderer) getTextureVariant(source engine.SpriteSource, frame, red, green, blue int, keyed bool) (*sdl.Texture, error) {
	key := textureKey{source: source, frame: frame, r: red, g: green, b: blue, keyed: keyed}

	if tex, ok := r.textures[key]; ok {
		return tex, nil
	}

	pixels, err := source.RGBA(frame)
	if err != nil {
		return nil, fmt.Errorf("render: decode frame %d: %w", frame, err)
	}

	w, h := source.Width(), source.Height()
	if w <= 0 || h <= 0 {
		return nil, fmt.Errorf("render: invalid source dimensions %dx%d", w, h)
	}

	if len(pixels) != w*h*4 {
		return nil, fmt.Errorf("render: pixel buffer len %d does not match %dx%d RGBA", len(pixels), w, h)
	}

	if keyed {
		if ks, ok := source.(engine.ColorKeySource); ok {
			kr, kg, kb, haveKey := ks.ColorKey()
			if haveKey {
				pixels = directDrawKeyedPixels(pixels, kr, kg, kb)
			}
		}
	}

	if red != 0 || green != 0 || blue != 0 {
		corrected := make([]byte, len(pixels))
		copy(corrected, pixels)
		for i := 0; i < len(corrected); i += 4 {
			if corrected[i+3] == 0 {
				continue
			}
			corrected[i] = addColor(corrected[i], red)
			corrected[i+1] = addColor(corrected[i+1], green)
			corrected[i+2] = addColor(corrected[i+2], blue)
		}
		pixels = corrected
	}

	// PixelFormatRGBA32 aliases ABGR8888, SDL's name for our in-memory byte
	// order R,G,B,A per pixel on a little-endian host.
	tex := sdl.CreateTexture(r.renderer, sdl.PixelFormatRGBA32, sdl.TextureAccessStatic, int32(w), int32(h))
	if tex == nil {
		return nil, fmt.Errorf("render: CreateTexture: %s", sdl.GetError())
	}

	sdl.SetTextureScaleMode(tex, sdl.ScaleModeNearest)
	sdl.SetTextureBlendMode(tex, sdl.BlendModeBlend)

	pitch := int32(w * 4)
	if !sdl.UpdateTexture(tex, nil, unsafe.Pointer(&pixels[0]), pitch) {
		sdl.DestroyTexture(tex)
		return nil, fmt.Errorf("render: UpdateTexture: %s", sdl.GetError())
	}

	r.textures[key] = tex

	return tex, nil
}

func addColor(value byte, delta int) byte {
	v := int(value) + delta
	if v < 0 {
		return 0
	}
	if v > 255 {
		return 255
	}
	return byte(v)
}

// Clear fills the logical screen with an opaque color.
func (r *Renderer) Clear(rr, gg, bb, aa uint8) {
	sdl.SetRenderDrawColor(r.renderer, rr, gg, bb, aa)
	sdl.RenderClear(r.renderer)
}

// Present flips the composed frame to the screen.
func (r *Renderer) Present() {
	sdl.RenderPresent(r.renderer)
}

// drawTopLeft draws source frame at (x, y) top-left-anchored, scaled by
// zoomPercent (100 == 1.0). Used for backgrounds and scene layers.
func (r *Renderer) drawTopLeft(source engine.SpriteSource, frame, x, y, zoomPercent int) error {
	return r.drawTopLeftVariant(source, frame, x, y, zoomPercent, false)
}

func (r *Renderer) drawTopLeftKeyed(source engine.SpriteSource, frame, x, y, zoomPercent int) error {
	return r.drawTopLeftVariant(source, frame, x, y, zoomPercent, true)
}

func (r *Renderer) drawTopLeftVariant(source engine.SpriteSource, frame, x, y, zoomPercent int, keyed bool) error {
	var tex *sdl.Texture
	var err error
	if keyed {
		tex, err = r.getTextureKeyed(source, frame)
	} else {
		tex, err = r.getTexture(source, frame)
	}
	if err != nil {
		return err
	}

	var dstW, dstH float32
	if keyed {
		dstW = float32(directDrawScaleExtent(source.Width(), zoomPercent))
		dstH = float32(directDrawScaleExtent(source.Height(), zoomPercent))
	} else {
		scale := float32(zoomPercent) / 100.0
		dstW = float32(source.Width()) * scale
		dstH = float32(source.Height()) * scale
	}

	dst := sdl.FRect{
		X: float32(x),
		Y: float32(y),
		W: dstW,
		H: dstH,
	}

	sdl.RenderTexture(r.renderer, tex, nil, &dst)

	return nil
}

func (r *Renderer) drawTopLeftMasked(source engine.SpriteSource, frame, x, y, zoomPercent int, bg *engine.Background, depth int) error {
	return r.drawTopLeftMaskedKeyed(source, frame, x, y, zoomPercent, bg, depth, false)
}

func (r *Renderer) drawTopLeftMaskedKeyed(source engine.SpriteSource, frame, x, y, zoomPercent int, bg *engine.Background, depth int, keyed bool) error {
	scale := float32(zoomPercent) / 100.0
	dst := sdl.FRect{
		X: float32(x),
		Y: float32(y),
		W: float32(source.Width()) * scale,
		H: float32(source.Height()) * scale,
	}
	return r.drawDepthMaskedKeyed(source, frame, dst, bg, depth, keyed)
}

