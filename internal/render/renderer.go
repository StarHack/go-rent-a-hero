func actorDestinationRect(source engine.SpriteSource, actorX, actorY float64, zoomPercent, anchorX, anchorY int) sdl.FRect {
	if zoomPercent == 0 {
		zoomPercent = 100
	}
	if anchorX == 0 && anchorY == 0 {
		anchorX, anchorY = 55, 162
	}

	scale := float32(zoomPercent) / 100.0
	return sdl.FRect{
		X: float32(actorX) - float32(anchorX)*scale,
		Y: float32(actorY) - float32(anchorY)*scale,
		W: float32(source.Width()) * scale,
		H: float32(source.Height()) * scale,
	}
}

