// actorPixelVisible implements the original per-pixel comparison recovered
// from dec(2).c: draw an actor pixel when actorDepth < sceneDepth.
//
// A zero scene-depth byte is treated as "no usable occluder" here so empty
// ZBF regions cannot punch artificial holes into the sprite.
func actorPixelVisible(actorDepth, sceneDepth int) bool {
	if sceneDepth == 0 {
		return true
	}
	return actorDepth < sceneDepth
}

