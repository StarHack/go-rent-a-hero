// Package render implements the SDL3-backed presentation layer: window,
// logical viewport, texture cache and scene composition. It depends on
// internal/engine's renderer-independent scene model but nothing in
// internal/engine depends back on SDL.
package render

import (
	"fmt"
	"unsafe"

	"github.com/jupiterrider/purego-sdl3/sdl"
	"github.com/wok/rent-a-hero/internal/engine"
)

// LogicalWidth and LogicalHeight are the full logical presentation size:
// the 640x360 playable scene viewport on top, with the remainder reserved
// for original UI/inventory presentation (see agents/IMPLEMENTATION.md
// "Logical coordinate system").
const (
	LogicalWidth  = 640
	LogicalHeight = 480

	SceneWidth  = 640
	SceneHeight = 360
)

// textureKey identifies one cached GPU texture: a specific decoded frame of
// a specific sprite source. SpriteSource implementations here are always
// backed by a pointer, so interface equality reduces to pointer identity.
type textureKey struct {
	source engine.SpriteSource
	frame  int
	r      int
	g      int
	b      int
	keyed  bool
}

// Renderer owns the SDL window/renderer and a texture cache keyed by
// (source, frame). Color-correction variants are not yet part of the cache
// key; per-pixel tinting lands in a later milestone.
type Renderer struct {
	window   *sdl.Window
	renderer *sdl.Renderer
	textures map[textureKey]*sdl.Texture

	debugAreas bool
	debugArea  bool

	// actorMask is a scratch texture reused (recreated only when its size
	// changes) for the per-pixel occlusion-masked actor draw, per
	// agents/techniques/SMOOTH-TRANSITIONS-ZBUFFER-GLIDER.MD sections
	// 10-13. Unlike the (source, frame) texture cache, its content depends
	// on the actor's current screen position, so it can't be a cache entry
	// keyed by source/frame -- it is instead overwritten every time an
	// actor is drawn against real background depth data.
	actorMask          *sdl.Texture
	actorMaskW         int32
	actorMaskH         int32
	actorMaskBuf       []byte // scratch RGBA buffer reused across frames, sized actorMaskW*actorMaskH*4
	inventoryMouseDown bool
	cursors            map[int]*sdl.Cursor
	cursorType         int
	hoverArea          string
	hoverSince         uint64
	hoverX             float32
	hoverY             float32
}

// New creates the SDL window and renderer, and configures the logical
// presentation so window resizing/high-DPI never affects game coordinates.
// fullscreen opens the window in (borderless desktop) fullscreen instead of
// a normal resizable window, per config.ini's full_screen.
func New(title string, windowWidth, windowHeight int32, fullscreen bool) (*Renderer, error) {
	if !sdl.Init(sdl.InitVideo) {
		return nil, fmt.Errorf("render: sdl.Init: %s", sdl.GetError())
	}

	windowFlags := sdl.WindowResizable
	if fullscreen {
		windowFlags |= sdl.WindowFullscreen
	}

	var window *sdl.Window
	var renderer *sdl.Renderer

	if !sdl.CreateWindowAndRenderer(title, windowWidth, windowHeight, windowFlags, &window, &renderer) {
		sdl.Quit()
		return nil, fmt.Errorf("render: CreateWindowAndRenderer: %s", sdl.GetError())
	}

	if !sdl.SetRenderLogicalPresentation(renderer, LogicalWidth, LogicalHeight, sdl.LogicalPresentationLetterbox) {
		sdl.DestroyRenderer(renderer)
		sdl.DestroyWindow(window)
		sdl.Quit()
		return nil, fmt.Errorf("render: SetRenderLogicalPresentation: %s", sdl.GetError())
	}

	// Best-effort: caps the render loop to the display's refresh rate so it
	// doesn't needlessly spin as fast as the GPU allows. Not required for
	// correctness -- the caller drives gameplay from a real-time
	// accumulator specifically so simulation speed never depends on this --
	// but avoids wasted CPU/GPU work and tearing. Some drivers don't
	// support toggling it, so a failure here is not fatal.
	sdl.SetRenderVSync(renderer, 1)

	r := &Renderer{
		window:   window,
		renderer: renderer,
		textures: map[textureKey]*sdl.Texture{},
	}
	r.initCursors()
	return r, nil
}

// Close destroys all cached textures, the renderer, the window, and shuts
// down the SDL video subsystem.
func (r *Renderer) Close() {
	for _, tex := range r.textures {
		sdl.DestroyTexture(tex)
	}
	r.textures = nil

	if r.actorMask != nil {
		sdl.DestroyTexture(r.actorMask)
		r.actorMask = nil
	}
	for _, cursor := range r.cursors {
		sdl.DestroyCursor(cursor)
	}
	r.cursors = nil

	sdl.DestroyRenderer(r.renderer)
	sdl.DestroyWindow(r.window)
	sdl.Quit()
}

