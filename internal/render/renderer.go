func (r *Renderer) drawDepthMaskedCorrectedKeyed(source engine.SpriteSource, frame int, dst sdl.FRect, bg *engine.Background, depth, red, green, blue int, keyed bool) error {
	srcW, srcH := source.Width(), source.Height()
	if srcW <= 0 || srcH <= 0 {
		return nil
	}

	dstW := int(dst.W)
	dstH := int(dst.H)
	if dstW <= 0 || dstH <= 0 {
		return nil
	}

	originX := int(dst.X)
	originY := int(dst.Y)

	pixels, err := source.RGBA(frame)
	if err != nil {
		return fmt.Errorf("render: decode frame %d: %w", frame, err)
	}
	if len(pixels) != srcW*srcH*4 {
		return fmt.Errorf("render: pixel buffer len %d does not match %dx%d RGBA", len(pixels), srcW, srcH)
	}

	var kr, kg, kb byte
	haveKey := false
	if keyed {
		if ks, ok := source.(engine.ColorKeySource); ok {
			kr, kg, kb, haveKey = ks.ColorKey()
		}
	}

	need := dstW * dstH * 4
	if cap(r.actorMaskBuf) < need {
		r.actorMaskBuf = make([]byte, need)
	}
	buf := r.actorMaskBuf[:need]

	for dy := 0; dy < dstH; dy++ {
		sy := dy * srcH / dstH
		for dx := 0; dx < dstW; dx++ {
			sx := dx * srcW / dstW

			si := (sy*srcW + sx) * 4
			di := (dy*dstW + dx) * 4

			rr := pixels[si]
			gg := pixels[si+1]
			bb := pixels[si+2]
			aa := pixels[si+3]
			if haveKey && directDrawKeyMatch(rr, gg, bb, kr, kg, kb) {
				aa = 0
			} else if haveKey && aa != 0 {
				rr, gg, bb = directDrawExpandRGB555(directDrawRGB555(rr, gg, bb))
				aa = 0xff
			}
			if aa != 0 {
				rr = addColor(rr, red)
				gg = addColor(gg, green)
				bb = addColor(bb, blue)
			}

			if aa != 0 {
				if sceneDepth, ok := bg.DepthAt(originX+dx, originY+dy); ok && !actorPixelVisible(depth, sceneDepth) {
					aa = 0
				}
			}

			buf[di] = rr
			buf[di+1] = gg
			buf[di+2] = bb
			buf[di+3] = aa
		}
	}

	tex, err := r.getActorMaskTexture(int32(dstW), int32(dstH))
	if err != nil {
		return err
	}

	if !sdl.UpdateTexture(tex, nil, unsafe.Pointer(&buf[0]), int32(dstW*4)) {
		return fmt.Errorf("render: UpdateTexture (depth mask): %s", sdl.GetError())
	}

	sdl.RenderTexture(r.renderer, tex, nil, &dst)
	return nil
}

// getActorMaskTexture returns the reusable scratch texture for
// drawFeetAnchoredMasked, (re)creating it only when the requested size
// changes.
func (r *Renderer) getActorMaskTexture(w, h int32) (*sdl.Texture, error) {
	if r.actorMask != nil && r.actorMaskW == w && r.actorMaskH == h {
		return r.actorMask, nil
	}

	if r.actorMask != nil {
		sdl.DestroyTexture(r.actorMask)
		r.actorMask = nil
	}

	tex := sdl.CreateTexture(r.renderer, sdl.PixelFormatRGBA32, sdl.TextureAccessStreaming, w, h)
	if tex == nil {
		return nil, fmt.Errorf("render: CreateTexture (actor mask): %s", sdl.GetError())
	}
	sdl.SetTextureScaleMode(tex, sdl.ScaleModeNearest)
	sdl.SetTextureBlendMode(tex, sdl.BlendModeBlend)

	r.actorMask = tex
	r.actorMaskW = w
	r.actorMaskH = h

	return tex, nil
}

