func (r *Renderer) setCursorType(cursorType int) {
	if cursorType == r.cursorType {
		return
	}
	cursor := r.cursors[cursorType]
	if cursor == nil {
		cursor = r.cursors[0]
		cursorType = 0
	}
	if cursor != nil {
		sdl.SetCursor(cursor)
	}
	r.cursorType = cursorType
}
